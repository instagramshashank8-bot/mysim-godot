 static Vector3 Resolve(Vector3[] flat, float x, float y, float z, out bool ok) {
  for (int i = 0; i < flat.Length; i++) { var q = flat[i]; if (q.X == x && q.Y == y && q.Z == z) { ok = true; return q; } }
  ok = false; return new Vector3(x, y, z);
 }
 public static Vector3[] Apply(Vector3[] source, string path) {
  if (System.Environment.GetEnvironmentVariable("MYSIM_SEAM_WELDS") != "1") return source;
  Seam seam = null;
  foreach (var sc in Seams()) if (sc.Resource == path) { seam = sc; break; }
  if (seam == null) return source;
  if (source.Length != seam.SrcTris * 3) throw new Exception("Seam weld source triangle count changed: " + path + " (" + source.Length / 3 + " != " + seam.SrcTris + ")");
  if (seam.Bridge.Length != seam.TriCount * 9) throw new Exception("Seam weld bridge table malformed: " + path);
  var outv = new Vector3[source.Length + seam.TriCount * 3];
  Array.Copy(source, outv, source.Length);
  int seenFaces = 0;
  for (int t = 0; t < seam.TriCount; t++) {
   int baseIdx = source.Length + t * 3;
   var w = new Vector3[3];
   for (int k = 0; k < 3; k++) {
    int j = t * 9 + k * 3;
    bool ok; var r = Resolve(source, seam.Bridge[j], seam.Bridge[j + 1], seam.Bridge[j + 2], out ok);
    if (!ok) throw new Exception("Seam weld vertex missing in source: " + path + " tri " + t + " corner " + k);
    outv[baseIdx + k] = r; w[k] = r;
   }
   double ux = w[1].X - w[0].X, uy = w[1].Y - w[0].Y, uz = w[1].Z - w[0].Z;
   double wx = w[2].X - w[0].X, wy = w[2].Y - w[0].Y, wz = w[2].Z - w[0].Z;
   double crx = uy * wz - uz * wy, cry = uz * wx - ux * wz, crz = ux * wy - uy * wx;
   double area = 0.5 * Math.Sqrt(crx * crx + cry * cry + crz * crz);
   if (area < 0.02 || area > 5.0) throw new Exception("Seam weld face area out of bounds: " + path + " tri " + t + " area " + area.ToString("0.000"));
   seenFaces++;
  }
  GD.Print("SEAM_WELD ", path, " bridgeTriangles=", seam.TriCount, " sourceTris=", source.Length / 3, " outputTris=", outv.Length / 3);
  return outv;
 }
